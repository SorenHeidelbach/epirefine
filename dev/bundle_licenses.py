#!/usr/bin/env python3
"""Write rust/THIRD_PARTY_LICENSES.txt: the licence texts of every crate compiled into EpiRefine's kernels.

The crates are the normal (not build-only, not dev) dependencies of the crate in rust/, followed from the lock file, for
each platform a wheel is built for. The texts are the crates' own licence files (LICENSE*, LICENCE*, COPYING*,
NOTICE*, UNLICENSE*, at the crate root and one directory below it, which catches C code a crate vendors, such as
libdeflate in libdeflate-sys). Crates with identical texts share one entry.

    python dev/bundle_licenses.py            # write the file
    python dev/bundle_licenses.py --check    # exit 1 if the file is not what the lock file gives (CI)

Needs cargo with the crates' sources downloaded (`cargo fetch`). Only the standard library is used.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "rust"
OUT = ROOT / "THIRD_PARTY_LICENSES.txt"
TARGETS = ("x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu", "x86_64-unknown-linux-musl",
           "aarch64-apple-darwin", "x86_64-apple-darwin")
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)([-._].*)?$", re.IGNORECASE)
SKIP_DIRS = {"src", "tests", "benches", "examples", "target", ".github", "docs", "doc"}


def crates(target: str) -> dict[str, dict]:
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform",
                                      target], cwd=ROOT, check=True, capture_output=True, text=True).stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, todo = set(), [root]
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return {i: packages[i] for i in seen}


def licence_files(manifest: Path) -> list[Path]:
    d = manifest.parent
    found = [f for f in sorted(d.iterdir()) if f.is_file() and LICENCE_FILE.match(f.name)]
    for sub in sorted(p for p in d.iterdir() if p.is_dir() and p.name not in SKIP_DIRS):
        found += [f for f in sorted(sub.iterdir()) if f.is_file() and LICENCE_FILE.match(f.name)]
    return found


def render() -> str:
    pkgs: dict[str, dict] = {}
    for t in TARGETS:
        pkgs.update(crates(t))
    by_text: dict[str, dict] = {}
    missing = []
    for p in sorted(pkgs.values(), key=lambda p: (p["name"], p["version"])):
        files = licence_files(Path(p["manifest_path"]))
        if not files:
            missing.append(f'{p["name"]} {p["version"]}')
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip("\n") + "\n"
            key = hashlib.sha256(text.encode()).hexdigest()
            entry = by_text.setdefault(key, {"text": text, "files": set(), "crates": []})
            entry["files"].add(f.relative_to(Path(p["manifest_path"]).parent).as_posix())
            label = f'{p["name"]} {p["version"]} ({p.get("license") or "licence file only"})'
            if label not in entry["crates"]:
                entry["crates"].append(label)
    if missing:
        sys.exit("no licence file found for: " + ", ".join(missing))
    out = ["Third-party licences of the compiled kernels of EpiRefine",
           "",
           "The compiled extension of EpiRefine (epirefine._kernels._core; MIT, see LICENSE) contains code of the Rust",
           "crates below, and libdeflate (C, MIT) through libdeflate-sys. Each crate is listed with its version and",
           "the licence it declares, followed by every licence file the crate ships. Crates with identical licence",
           "texts share one entry. Generated by dev/bundle_licenses.py from rust/Cargo.lock; do not edit by hand.",
           ""]
    entries = sorted(by_text.values(), key=lambda e: (e["crates"][0], sorted(e["files"])))
    for e in entries:
        out += ["=" * 100, "Crates: " + "; ".join(e["crates"]), "File: " + ", ".join(sorted(e["files"])), "-" * 100,
                e["text"].rstrip("\n"), ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the file differs from what the lock file gives")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.name} is out of date: run python dev/bundle_licenses.py")
        print(f"{OUT.name} is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.name}: {len(text):,} characters")


if __name__ == "__main__":
    main()

"""Option E pinned to stored output of the explicit E options before E became the default (review test gap).

The golden snapshot (test_golden.py) is matched by both option E and --relatives switch, since the switch chooses
community only on that community, so it cannot tell them apart. On the sister community (synth.SISTERS, seed 1)
the switch chooses relatives and the two paths differ (the switch collapses p_unknown to 1 at T 1.715; E decides
at T 5.857). tests/data/sisters_e_decisions.tsv and sisters_e_params.json were written from a run of commit
28eeb94 (model/option-e) with --relatives community-only --unknown-share t1, from a snapshot with the compiled
kernels (epirefine-rs fe87834); a3560c4 (model/calibration-core) with the same options gives the same decision
files byte for byte. They are not regenerated by EPIREFINE_UPDATE_GOLDEN: a difference means option E changed.
fitted_temperature is not pinned: since review F2 it is the community-only fit's own (it was the switch's).
"""
import json

import test_golden as golden

DATA = golden.DATA
PINNED = DATA / "sisters_e_decisions.tsv"
PINNED_PARAMS = DATA / "sisters_e_params.json"


def _differences(run) -> list[str]:
    want = PINNED.read_text().splitlines()
    got = golden._snapshot(run)
    header = want[0].split("\t")
    assert got[0].split("\t") == header
    exp = {line.split("\t")[0]: line.split("\t") for line in want[1:]}
    new = {line.split("\t")[0]: line.split("\t") for line in got[1:]}
    assert exp.keys() == new.keys()
    diff = []
    for c in sorted(exp):
        for name, a, b in zip(header[1:], exp[c][1:], new[c][1:]):
            if not (a == b if name in golden.LABELS else golden._same_number(a, b)):
                diff.append(f"{c}: {name} {a} -> {b}")
    return diff


def test_default_equals_the_stored_explicit_e_run(sisters_run):
    diff = _differences(sisters_run)
    assert not diff, f"{len(diff)} differences from tests/data/{PINNED.name}:\n  " + "\n  ".join(diff[:40])
    want = json.loads(PINNED_PARAMS.read_text())
    got = golden._params(sisters_run)
    bad = [f"{k}: {want[k]} -> {got[k]}" for k in want if not golden._close(want[k], got[k])]
    assert not bad, bad


def test_the_pin_tells_option_e_from_the_switch(sisters_switch_run):
    statuses = [d for d in _differences(sisters_switch_run) if ": status " in d]
    assert len(statuses) >= 50
    assert json.loads((sisters_switch_run.out / "params.json").read_text())["unknown_lam"] < 1
